// The pitch deck's generator (plan Section 14.3). deck/index.html is the deck;
// this script writes its theme from the tokens, checks it, and exports it.
//
// The checks, run on the deck as Chrome renders it at 1920 by 1080:
//   every figure sits in an element marked data-claim whose id is a row of
//   docs/claims.md, and every digit in it appears in that row; any other digit
//   (a date, an id, a clause number) sits in an element marked data-ref; the
//   notes carry only figures shown on their slide; the receipt on slide 1 is in
//   its source in mcp/sample-workspace.json, with its employer, title, dates and
//   the reviewed denominator; the cells of the two graphics on slide 3 match
//   their figures; each quoted clause is word for word in src/data/accreditors.ts;
//   no text runs into a footer or off a slide; every image loads; no en or em dash.
// The exports, into deck/export/ (not committed; run this again after any edit):
//   slides/slide-NN.png at 2x, lyceum-deck.pdf (vector text, one page a slide)
//   and lyceum-deck.pptx (one 2x image per slide, the notes as speaker notes, the
//   film on slide 5 as a media object once deck/media/loop90.mp4 exists). On
//   Windows with PowerPoint, the PPTX is then opened in PowerPoint and its slide
//   count, notes and media are read back; the PDF's pages and text are read back
//   with unpdf and their digits checked against the same register.
// Usage: node scripts/gen-deck.mjs [--check]   (--check: theme and content only, no export)
import { spawnSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, rmSync, statSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { pathToFileURL } from "node:url";
import puppeteer from "puppeteer-core";
import pptxgen from "pptxgenjs";
import { extractText, getDocumentProxy } from "unpdf";
import { ROOT, fontFaceCss, fontsReady, rootVarsCss } from "./lib/theme-node.mjs";
import { claimsRegister, digitsIn, hasNumber as has } from "./lib/claims-node.mjs";
import { ACCREDITOR_MAPPING } from "../src/data/accreditors.ts";
import { loadWorkspace } from "../mcp/workspace.ts";
import { SAMPLE_PATH } from "../mcp/sample.ts";

const DECK = join(ROOT, "deck"), THEME = join(DECK, "theme.generated.css"), OUT = join(DECK, "export");
const FILM = join(DECK, "media", "loop90.mp4");
const CHECK_ONLY = process.argv.includes("--check");
const problems = [];
const DASH = new RegExp("[" + String.fromCharCode(0x2013, 0x2014) + "]");

// ---------- 1. the theme, from the tokens ----------
const theme = "/* Generated by scripts/gen-deck.mjs from src/theme/tokens.ts and the bundled fonts in public/fonts. Do not edit. */\n" + rootVarsCss() + "\n" + fontFaceCss() + "\n";
if (CHECK_ONLY) {
  if (!existsSync(THEME) || readFileSync(THEME, "utf8").replace(/\r\n/g, "\n") !== theme) problems.push("deck/theme.generated.css is stale; run node scripts/gen-deck.mjs.");
} else writeFileSync(THEME, theme);

// ---------- 2. the claims register (scripts/lib/claims-node.mjs) ----------
const REGISTER = claimsRegister();

// ---------- 3. render and read the deck ----------
const executablePath = ["C:/Program Files/Google/Chrome/Application/chrome.exe", "C:/Program Files (x86)/Google/Chrome/Application/chrome.exe", "C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe", "C:/Program Files/Microsoft/Edge/Application/msedge.exe"].find(existsSync);
if (!executablePath) throw new Error("Chrome or Edge must be installed");
const browser = await puppeteer.launch({ executablePath, headless: true });
let read, notes = [];
try {
  const page = await browser.newPage();
  const errors = [];
  page.on("pageerror", (e) => errors.push(String(e)));
  page.on("requestfailed", (r) => { if (!r.url().endsWith("loop90.mp4")) errors.push("could not load " + r.url()); });
  await page.setViewport({ width: 1920, height: 1080, deviceScaleFactor: 2 });
  await page.goto(pathToFileURL(join(DECK, "index.html")).href + "?export#1", { waitUntil: "load" });
  await fontsReady(page);
  await page.evaluate(() => Promise.all([...document.images].map((img) => img.decode().catch(() => null))));
  read = await page.evaluate(() => {
    const out = [];
    const slides = [...document.querySelectorAll(".slide")];
    slides.forEach((slide, i) => {
      window.deck.show(i);
      const box = slide.getBoundingClientRect();
      const foot = slide.querySelector(".foot")?.getBoundingClientRect();
      const r = { title: slide.dataset.title, stray: [], claims: [], refs: [], clipped: [], images: [], text: "", notes: slide.querySelector(".notes")?.textContent.trim() ?? "" };
      const walker = document.createTreeWalker(slide, NodeFilter.SHOW_TEXT);
      for (let n = walker.nextNode(); n; n = walker.nextNode()) {
        const el = n.parentElement;
        if (!n.textContent.trim() || el.closest(".notes")) continue;
        r.text += " " + n.textContent;
        if (/\d/.test(n.textContent) && !el.closest("[data-claim], [data-ref], .slide-number")) r.stray.push(n.textContent.trim());
        // Text must stay on the slide and above its footer.
        if (!el.closest(".foot")) {
          const range = document.createRange(); range.selectNodeContents(n);
          const t = range.getBoundingClientRect();
          if (t.width && (t.right > box.right - 40 || t.left < box.left + 40 || t.bottom > (foot ? foot.top - 8 : box.bottom - 40))) r.clipped.push(n.textContent.trim().slice(0, 60));
        }
      }
      for (const el of slide.querySelectorAll("[data-claim]")) r.claims.push({ id: el.dataset.claim, text: el.textContent.replace(/\s+/g, " ").trim() });
      for (const el of slide.querySelectorAll("[data-ref]")) r.refs.push(el.textContent.replace(/\s+/g, " ").trim());
      for (const img of slide.querySelectorAll("img")) { r.images.push({ src: img.getAttribute("src"), ok: img.complete && img.naturalWidth > 0, alt: img.getAttribute("alt") ?? "" }); r.text += " " + (img.getAttribute("alt") ?? ""); }
      for (const el of slide.querySelectorAll("[aria-label]")) r.text += " " + el.getAttribute("aria-label");
      out.push(r);
    });
    const receipt = document.querySelector("[data-receipt]");
    const cells = (sel) => document.querySelectorAll(sel).length;
    return {
      slides: out,
      receipt: receipt && { hash: receipt.dataset.sourceHash, quote: receipt.querySelector("[data-quote]").textContent, meta: receipt.querySelector(".receipt-meta").textContent, link: receipt.querySelector(".receipt-link").textContent, count: receipt.querySelector("[data-claim] .big").textContent },
      waffle: { on: cells(".waffle i.on"), all: cells(".waffle i") }, calendar: { on: cells(".calendar i.on"), all: cells(".calendar i") },
      clauses: [...document.querySelectorAll("[data-clause]")].map((q) => ({ clause: q.dataset.clause, text: q.textContent })),
    };
  });
  if (errors.length) problems.push(...errors.map((e) => "Deck page: " + e));
  // The film on slide 5, once rendered: Chrome must load it from deck/media, as the presenting laptop will.
  if (existsSync(FILM)) {
    const film = await page.evaluate(async () => {
      const v = document.querySelector(".film video");
      v.preload = "metadata";
      v.load();
      try {
        await new Promise((res, rej) => { v.onloadedmetadata = res; v.onerror = () => rej(new Error("the browser could not decode it")); setTimeout(() => rej(new Error("it did not load in 15 s")), 15000); });
        return { seconds: v.duration, width: v.videoWidth, height: v.videoHeight };
      } catch (e) { return { error: String(e.message ?? e) }; }
    });
    if (film.error) problems.push("The film on slide 5 does not play in Chrome: " + film.error);
    else if (film.width !== 1920 || film.height !== 1080 || film.seconds < 60) problems.push("The film on slide 5 is " + film.width + " by " + film.height + " and " + film.seconds.toFixed(1) + " s; expected the 1920 by 1080 Loop90 cut.");
    else console.log("The film loads on slide 5: " + film.seconds.toFixed(1) + " s at " + film.width + " by " + film.height + ".");
  }

  // ---------- 4. the checks ----------
  read.slides.forEach((s, i) => {
    const where = "Slide " + (i + 1) + " (" + s.title + ")";
    for (const t of s.stray) problems.push(where + ": a digit outside a data-claim or data-ref element: " + t);
    for (const t of s.clipped) problems.push(where + ": text runs off the slide or into the footer: " + t);
    for (const img of s.images) { if (!img.ok) problems.push(where + ": image did not load: " + img.src); }
    if (DASH.test(s.text + s.notes)) problems.push(where + ": an en or em dash.");
    if (!s.notes) problems.push(where + ": no speaker notes.");
    const allowed = [];
    for (const c of s.claims) {
      const row = REGISTER.get(c.id);
      if (!row) { problems.push(where + ": data-claim " + c.id + " is not a row of docs/claims.md."); continue; }
      allowed.push(row);
      for (const d of digitsIn(c.text)) if (!has(row, d)) problems.push(where + ": " + d + " in " + c.id + " is not in its claims row.");
    }
    // Notes may speak a figure shown on their slide, a reference shown on it, or a cue like 0:30.
    for (const d of digitsIn(s.notes.replace(/\b\d:\d\d\b/g, ""))) if (![...allowed, ...s.refs].some((t) => has(t, d))) problems.push(where + ": the notes speak " + d + ", which the slide does not show from the register.");
  });
  const r = read.receipt;
  const sample = loadWorkspace(SAMPLE_PATH);
  if (!sample.ok) problems.push("The sample workspace did not load: " + sample.error);
  else if (!r) problems.push("Slide 1 has no receipt.");
  else {
    const d = sample.backup.data, src = d.evidenceSources.find((s) => s.textHash === r.hash);
    const quote = r.quote.replace(/^[\u201C"]|[\u201D"]$/g, "");
    const reviewed = d.evidenceSources.filter((s) => s.subjectId === "CS310" && s.reviewed && !s.duplicateOf).length;
    if (!src) problems.push("The receipt's fingerprint " + r.hash + " is not a source in the sample.");
    else {
      if (!src.text.includes(quote)) problems.push("The receipt's sentence is not in its source text.");
      if (!d.skillMentions.some((m) => m.sourceId === src.id && m.excerpt === quote)) problems.push("The receipt's sentence is not a confirmed quotation of its source.");
      for (const [what, value] of [["employer", src.organisation], ["title", src.title], ["published date", src.sourceDate]]) if (!r.meta.includes(value)) problems.push("The receipt's " + what + " is not " + value + ".");
      if (!r.link.includes(src.url.replace(/^https?:\/\//, "")) || !r.link.includes(src.collection.retrievedAt.slice(0, 10)) || !r.link.includes(src.textHash)) problems.push("The receipt's link, retrieval date or fingerprint does not match its source.");
    }
    if (!new RegExp("of " + reviewed + "\\b").test(r.count)) problems.push("The receipt says " + r.count + "; the sample has " + reviewed + " reviewed postings for CS310.");
  }
  const latency = REGISTER.get("world-skills-and-approval") ?? "";
  if (read.waffle.all !== 100 || !latency.includes(read.waffle.on + "%")) problems.push("The waffle shows " + read.waffle.on + " of " + read.waffle.all + "; the register says otherwise.");
  if (!latency.includes(read.calendar.on + " to " + read.calendar.all + " months")) problems.push("The calendar shows " + read.calendar.on + " to " + read.calendar.all + " months; the register says otherwise.");
  const quotes = new Map(ACCREDITOR_MAPPING.flatMap((s) => s.clauses).map((c) => [c.body, c.quote]));
  for (const q of read.clauses) if (!quotes.get(q.clause)?.includes(q.text)) problems.push("Slide 10 quotes " + q.clause + " in words its note does not hold: " + q.text);
  notes = read.slides.map((s) => s.notes);

  // ---------- 5. the exports ----------
  if (!CHECK_ONLY && !problems.length) {
    rmSync(OUT, { recursive: true, force: true });
    mkdirSync(join(OUT, "slides"), { recursive: true });
    const shots = [];
    for (let i = 0; i < read.slides.length; i += 1) {
      await page.evaluate((k) => window.deck.show(k), i);
      const file = join(OUT, "slides", "slide-" + String(i + 1).padStart(2, "0") + ".png");
      await page.screenshot({ path: file, clip: { x: 0, y: 0, width: 1920, height: 1080 } });
      shots.push(file);
    }
    await page.pdf({ path: join(OUT, "lyceum-deck.pdf"), width: "1920px", height: "1080px", printBackground: true, preferCSSPageSize: true });

    const pptx = new pptxgen();
    pptx.layout = "LAYOUT_WIDE"; // 13.333 by 7.5 inches, 16:9
    pptx.title = "Lyceum: a course decision with receipts";
    pptx.author = "Lyceum team";
    pptx.subject = "HACKaSTONE 2026 Grand Final pitch";
    const film = existsSync(FILM);
    shots.forEach((file, i) => {
      const slide = pptx.addSlide();
      slide.addImage({ path: file, x: 0, y: 0, w: 13.333, h: 7.5, altText: read.slides[i].title });
      if (film && read.slides[i].title === "Watch and Report") slide.addMedia({ type: "video", path: FILM, x: 0, y: 0, w: 13.333, h: 7.5, cover: "data:image/png;base64," + readFileSync(file).toString("base64") });
      slide.addNotes(notes[i]);
    });
    await pptx.writeFile({ fileName: join(OUT, "lyceum-deck.pptx") });
    console.log("Exported " + shots.length + " slides: deck/export/slides at 2x, lyceum-deck.pdf (" + kb(join(OUT, "lyceum-deck.pdf")) + ") and lyceum-deck.pptx (" + kb(join(OUT, "lyceum-deck.pptx")) + ")" + (film ? ", the film on slide 5." : "; the film is not in deck/media yet, so slide 5 carries its image only."));
  }
} finally { await browser.close(); }

// ---------- 6. read the exports back ----------
if (!CHECK_ONLY && !problems.length) {
  const pdf = await getDocumentProxy(new Uint8Array(readFileSync(join(OUT, "lyceum-deck.pdf"))));
  const { totalPages, text } = await extractText(pdf, { mergePages: false });
  if (totalPages !== read.slides.length) problems.push("The PDF has " + totalPages + " pages for " + read.slides.length + " slides.");
  text.forEach((pageText, i) => {
    const s = read.slides[i];
    if (!s) return;
    const allowed = [...s.claims.map((c) => REGISTER.get(c.id) ?? ""), ...s.refs, (i + 1) + " / " + read.slides.length];
    for (const d of digitsIn(pageText)) if (!allowed.some((t) => has(t, d))) problems.push("PDF page " + (i + 1) + ": " + d + " is neither a registered figure nor a reference on that slide.");
    if (DASH.test(pageText)) problems.push("PDF page " + (i + 1) + ": an en or em dash.");
  });
  console.log("Read the PDF back: " + totalPages + " pages, every digit a registered figure or a reference on its slide.");
  const powerpoint = ["C:/Program Files/Microsoft Office/root/Office16/POWERPNT.EXE", "C:/Program Files (x86)/Microsoft Office/root/Office16/POWERPNT.EXE"].some(existsSync);
  if (process.platform === "win32" && powerpoint) {
    const run = spawnSync("powershell", ["-NoProfile", "-ExecutionPolicy", "Bypass", "-File", join(ROOT, "scripts/render-pptx.ps1"), "-In", join(OUT, "lyceum-deck.pptx")], { encoding: "utf8", timeout: 180000 });
    if (run.status !== 0) problems.push("PowerPoint could not open the deck: " + (run.stderr || run.stdout).slice(0, 400));
    else {
      const opened = JSON.parse(run.stdout);
      const flat = (s) => s.replace(/\s+/g, " ").trim();
      if (opened.slides !== read.slides.length) problems.push("PowerPoint read " + opened.slides + " slides.");
      opened.detail.forEach((d, i) => { if (flat(d.notes) !== flat(notes[i])) problems.push("PowerPoint reads different notes on slide " + (i + 1) + "."); });
      const media = opened.detail.reduce((n, d) => n + d.media, 0);
      if (existsSync(FILM) && media !== 1) problems.push("PowerPoint finds " + media + " media objects; the film should be one, on slide 5.");
      console.log("Opened the PPTX in PowerPoint: " + opened.slides + " slides at " + opened.width + " by " + opened.height + " points, every slide's notes as written, " + media + " media object" + (media === 1 ? "" : "s") + ".");
    }
  } else console.log("PowerPoint is not installed here; open deck/export/lyceum-deck.pptx in PowerPoint to check the notes and the film.");
}

function kb(file) { return Math.round(statSync(file).size / 1024) + " KB"; }

if (problems.length) {
  console.error("DECK CHECK FAILED\n  " + problems.join("\n  "));
  process.exit(1);
}
console.log((CHECK_ONLY ? "Deck check passed: " : "Deck checks passed: ") + read.slides.length + " slides, " + read.slides.reduce((n, s) => n + s.claims.length, 0) + " figures in the claims register, the receipt in its source, the clauses word for word, no dash.");
